  function t(key) {
    return FIELD[key] || key;
  }

  /* 枚举翻译：对字段 field 的值 val 翻译；无对应返回 val 本身 */
  function e(field, val) {
    if (val == null || val === "") return val;
    const m = ENUM[field];
    return (m && m[val]) || val;
  }

  /* 读 horse[field] 并翻译（字段名和枚举都翻译）；缺值返回 def */
  function g(h, field, def) {
    const v = h == null ? undefined : h[field];
    if (v == null || v === "") return def == null ? "" : def;
    return e(field, v);
  }

  /* 翻译 収得賞金 对象：{平地,障害,Jpn} → [{k:中文,v:金额}] */
  function prizeEntries(prize) {
    if (!prize || typeof prize !== "object") return [];
    return Object.keys(prize).map(function (k) {
      return { k: t(k), v: prize[k] };
    }).filter(function (x) { return x.v != null && x.v !== 0; });
  }

  return { t, e, g, prizeEntries };
